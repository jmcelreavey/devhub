import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it, expect, vi, afterAll } from "vitest";
const fixture = vi.hoisted(() => ({ root: "" }));
vi.mock("@/lib/desktop/runtime-paths", () => ({ defaultAppDataDir: () => fixture.root, getResourceRoot: () => path.resolve(process.cwd(), "..") }));
vi.mock("@/lib/tasks/profiles", () => ({ getTaskProfileOverview: () => ({ active: "browser-smoke" }) }));
vi.mock("@/lib/notes/dir", () => ({ getActiveTasksDir: () => fixture.root }));
vi.mock("@shared/tasks/store", () => ({ findTask: () => ({ id: "fixture", done: false }) }));
vi.mock("@/lib/tasks/task-agent-runs", () => ({ listTaskAgentRuns: () => [{ runId: "fixture-run", status: "running" }] }));
import { startBrowser, stopBrowser, currentBrowser, browserStatus } from "./runtime";
import { execExternal } from "@/lib/exec-external";
import { resumeBrowser, browserCredential, browserRequest, browserObserve, approveBrowserAction, takeBrowserControl, browserScreenshot } from "./commands";

describe.skipIf(process.env.DEVHUB_BROWSER_SMOKE !== "1")("owned native Chrome", () => {
  afterAll(async () => { await stopBrowser(); if (fixture.root) fs.rmSync(fixture.root, { recursive: true, force: true }); });
  it("persists only its fixture profile, gates actions, pauses login capture and revokes old access", async () => {
    fixture.root = fs.mkdtempSync(path.join(os.tmpdir(), "devhub-browser-smoke-"));
    await startBrowser({ taskId: "fixture", runId: "fixture-run", origins: ["https://example.com"], persistent: true, consent: true });
    const first = currentBrowser();
    const port = Number(fs.readFileSync(path.join(first.dir, "DevToolsActivePort"), "utf8").split("\n")[0]);
    const listeners = await execExternal("lsof", ["-nP", "-iTCP:" + port, "-sTCP:LISTEN"], { timeoutMs: 5000, label: "browser:smoke-listener" });
    expect(listeners.stdout).toContain("127.0.0.1:" + port);
    expect(listeners.stdout).not.toMatch(/\*:\d+|0\.0\.0\.0:/);
    const diagnostic = await first.browser.newBrowserCDPSession();
    const processInfo = await diagnostic.send("SystemInfo.getProcessInfo");
    const usage = await execExternal("ps", ["-p", processInfo.processInfo.map((item) => item.id).join(","), "-o", "rss=,%cpu="], { timeoutMs: 5000, label: "browser:smoke-resources" });
    const rows = usage.stdout.trim().split("\n").map((row) => row.trim().split(/\s+/).map(Number));
    console.log(JSON.stringify({ ownedChromeProcesses: rows.length, startupRssMiB: Math.round(rows.reduce((sum, row) => sum + row[0], 0) / 1024), startupCpuPercent: rows.reduce((sum, row) => sum + row[1], 0), listener: "IPv4 loopback only" }));
    await diagnostic.detach();
    await first.context.route("https://example.com/**", (route) => route.fulfill({ contentType: "text/html", body: '<html><body><h1>Browser fixture</h1><label>Message<input aria-label="Message"></label><button onclick="document.querySelector(\'h1\').textContent=\'Submitted\'">Submit</button></body></html>' }));
    await first.page.goto("https://example.com/fixture");
    await first.context.addCookies([{ name: "devhub_fixture", value: "test-only", domain: "example.com", path: "/", expires: Math.floor(Date.now() / 1000) + 3600 }]);
    const initial = await resumeBrowser(first.view.id);
    expect(initial.text).toContain("Browser fixture");
    const access = browserCredential("fixture", "fixture-run");
    expect(() => browserCredential("wrong", "fixture-run")).toThrow();
    const target = initial.elements.find((item) => item.name === "Message")!;
    const request = await browserRequest(access.sessionId, access.lease, { kind: "type", target: target.id, observation: initial.id, text: "A test value" });
    expect(request).toHaveProperty("awaitingApproval", true);
    expect(await first.page.locator("input").inputValue()).toBe("");
    const proposalId = first.view.pending!.id;
    await approveBrowserAction(first.view.id, proposalId);
    expect(await first.page.locator("input").inputValue()).toBe("A test value");
    await expect(approveBrowserAction(first.view.id, proposalId)).rejects.toThrow();
    expect((await browserScreenshot(first.view.id)).length).toBeGreaterThan(100);
    await takeBrowserControl(first.view.id);
    await expect(browserObserve(first.view.id, access.lease)).rejects.toThrow();
    await expect(browserScreenshot(first.view.id)).rejects.toThrow();
    await resumeBrowser(first.view.id);
    await first.page.setContent('<input type="password"><p>Private sign-in</p>');
    await expect(browserScreenshot(first.view.id)).rejects.toThrow("Sign-in");
    await stopBrowser();
    expect(browserStatus().session).toBeNull();
    await startBrowser({ taskId: "fixture", runId: "fixture-run", origins: ["https://example.com"], persistent: true, consent: true });
    expect((await currentBrowser().context.cookies("https://example.com")).some((cookie) => cookie.name === "devhub_fixture")).toBe(true);
    expect(currentBrowser().lease.mode).toBe("human");
    await stopBrowser();
  }, 60_000);
  it("streams, resizes, sends Unicode and scroll input, handles popups and gates files", async () => {
    await startBrowser({ taskId: "fixture", runId: "fixture-run", origins: ["https://example.com"], persistent: true, consent: true });
    const session = currentBrowser(), surface = session.surface!;
    await session.context.route("https://example.com/**", (route) => {
      if (route.request().url().endsWith("/download")) return route.fulfill({ status: 200, headers: { "content-type": "application/octet-stream", "content-disposition": 'attachment; filename="fixture.txt"' }, body: "approved download fixture" });
      return route.fulfill({ contentType: "text/html", body: '<html><body><input aria-label="Message"><input type="file"><button onclick="window.open(\'/popup\')">Popup</button><a href="/download">Download</a><div style="height:3000px">Scroll fixture</div></body></html>' });
    });
    await session.page.goto("https://example.com/fixture");
    let streamId = "", frames = 0;
    const stop = await surface.openStream((event, data) => {
      if (event === "ready") streamId = (data as { id: string }).id;
      if (event === "frame") frames++;
      return true;
    });
    await vi.waitFor(() => expect(frames).toBeGreaterThan(0));
    await surface.input(streamId, { kind: "resize", width: 800, height: 500, dpr: 2 });
    expect(await session.page.evaluate(() => [innerWidth, innerHeight, devicePixelRatio])).toEqual([800, 500, 2]);
    await surface.input(streamId, { kind: "click", x: 60, y: 18, button: "left", count: 1 });
    await surface.input(streamId, { kind: "text", text: "日本語 café 🦊" });
    expect(await session.page.locator('input[aria-label="Message"]').inputValue()).toBe("日本語 café 🦊");
    await surface.input(streamId, { kind: "scroll", x: 400, y: 250, deltaX: 0, deltaY: 400 });
    await vi.waitFor(async () => expect(await session.page.evaluate(() => scrollY)).toBeGreaterThan(0));
    await session.page.locator('input[type="file"]').click();
    await vi.waitFor(() => expect(session.view.transfer?.kind).toBe("upload"));
    const uploadId = session.view.transfer!.id;
    expect(await session.page.locator('input[type="file"]').evaluate((node) => (node as HTMLInputElement).files?.length)).toBe(0);
    await surface.upload(uploadId, { name: "fixture.txt", mimeType: "text/plain", buffer: Buffer.from("approved upload") });
    expect(await session.page.locator('input[type="file"]').evaluate((node) => (node as HTMLInputElement).files?.[0]?.name)).toBe("fixture.txt");
    await expect(surface.upload(uploadId, { name: "replay", mimeType: "text/plain", buffer: Buffer.from("x") })).rejects.toThrow();
    await session.page.getByText("Popup", { exact: true }).click();
    await vi.waitFor(() => expect(session.view.tabs).toHaveLength(2));
    const popup = session.view.tabs!.find((tab) => tab.id !== session.view.activeTab)!;
    await surface.selectTab(popup.id);
    expect(session.page.url()).toContain("/popup");
    await expect(surface.input(streamId, { kind: "text", text: "stale" })).rejects.toThrow("live view changed");
    await surface.selectTab(popup.id, true);
    await session.page.getByText("Download", { exact: true }).click({ noWaitAfter: true });
    await vi.waitFor(() => expect(session.view.transfer?.kind).toBe("download"));
    const downloadId = session.view.transfer!.id;
    expect((await surface.download(downloadId)).toString()).toBe("approved download fixture");
    await expect(surface.download(downloadId)).rejects.toThrow("expired");
    await stop();
    await stopBrowser();
  }, 60_000);
});
