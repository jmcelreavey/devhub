#!/usr/bin/env node
// Run after changing core API or Vite routes. No route modules are executed.
import { readdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ui = path.join(root, "apps/ui");
const api = path.join(root, "apps/core/src/http/routes");
const output = path.join(root, "apps/core/src/http/routes.generated.ts");
const methods = new Set(["GET", "HEAD", "OPTIONS", "POST", "PUT", "PATCH", "DELETE"]);

function walk(dir, include) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(file, include) : entry.isFile() && include(entry.name) ? [file] : [];
  });
}

// Mirror the namespace rules in lib/plugins/alias-contract.ts. Use the files
// on disk so newly added routes are reserved before they are staged in Git.
const app = path.join(ui, "app");
const isRouteFile = name => /(?:page|route)\.(?:tsx?|jsx?)$/.test(name);
const appFiles = [
  ...walk(app, isRouteFile).map(file => path.relative(app, file)),
  ...walk(api, isRouteFile).map(file => path.join("api", path.relative(api, file))),
];
const appNamespaces = appFiles.map(file => {
  const segments = file.split(path.sep).slice(0, -1)
    .filter(segment => !segment.startsWith("(") && !segment.startsWith("@"));
  const route = "/" + segments.join("/");
  const namespace = route.split("/").slice(0, route.startsWith("/api/") ? 3 : 2).join("/");
  return namespace.includes("[") ? namespace.startsWith("/api/") ? "/api" : "/*" : namespace;
}).filter(namespace => namespace !== "/");
const routeDir = path.join(ui, "src/routes");
const clientPaths = readdirSync(routeDir).filter(file => file.endsWith(".tsx")).flatMap(file =>
  [...readFileSync(path.join(routeDir, file), "utf8").matchAll(/\bpath:\s*["'](\/[^"']*)["']/g)].map(match => match[1]));
const namespaces = [...new Set([
  ...appNamespaces,
  ...clientPaths.map(value => value.split("/").slice(0, 2).join("/")).filter(value => value !== "/"),
])].sort();
if (!namespaces.length) throw new Error("Cannot determine core route ownership");
writeFileSync(path.join(path.dirname(output), "namespaces.generated.ts"), [
  "// Generated by scripts/gen-core-routes.mjs; do not edit.",
  `export const coreRouteNamespaces: string[] = ${JSON.stringify(namespaces)};`,
  "",
].join("\n"));

function resolveImport(file, specifier) {
  let base;
  if (specifier.startsWith("@/")) base = path.join(ui, specifier.slice(2));
  else if (specifier.startsWith("@shared/plugin-registry/")) base = path.join(root, "packages/shared/plugin-registry", specifier.slice(24));
  else if (specifier.startsWith("@shared/")) base = path.join(root, "packages/shared", specifier.slice(8));
  else if (specifier.startsWith("@contracts/")) base = path.join(root, "packages/shared", specifier.slice(11));
  else if (specifier.startsWith(".")) base = path.resolve(path.dirname(file), specifier);
  else return null;
  return [base, `${base}.ts`, `${base}.tsx`, `${base}.js`, path.join(base, "index.ts"), path.join(base, "index.tsx")]
    .find(candidate => existsSync(candidate) && /\.[cm]?[jt]sx?$/.test(candidate)) ?? null;
}

const sources = new Map();
function source(file) {
  if (!sources.has(file)) sources.set(file, readFileSync(file, "utf8"));
  return sources.get(file);
}

function unsupported(file, seen = new Set()) {
  if (seen.has(file)) return [];
  seen.add(file);
  const text = source(file);
  const problems = [];
  const imports = /(?:import|export)\s+(?!type\b)([\s\S]*?)\s+from\s*["']([^"']+)["']|\bimport\s*\(\s*["']([^"']+)["']\s*\)/g;
  for (const match of text.matchAll(imports)) {
    const specifier = match[2] ?? match[3];
    if (/^next(?:\/|$)/.test(specifier)) {
      problems.push(`${path.relative(root, file)}: ${specifier}`);
    }
    const dependency = resolveImport(file, specifier);
    if (dependency) problems.push(...unsupported(dependency, seen));
  }
  return [...new Set(problems)].sort();
}

function exportedMethods(text, file) {
  const found = new Set();
  for (const match of text.matchAll(/\bexport\s+(?:async\s+)?(?:function|const|let|var)\s+(GET|HEAD|OPTIONS|POST|PUT|PATCH|DELETE)\b/g)) found.add(match[1]);
  for (const match of text.matchAll(/\bexport\s+(?:const|let|var)\s*\{([^}]+)\}/g)) {
    for (const name of match[1].split(",").map(part => part.trim())) if (methods.has(name)) found.add(name);
  }
  for (const match of text.matchAll(/\bexport\s*\{([^}]+)\}/g)) {
    for (const part of match[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/).at(-1);
      if (methods.has(name)) found.add(name);
    }
  }
  if (!found.size) throw new Error(`No HTTP methods found in ${path.relative(root, file)}`);
  return [...found].sort();
}

const routes = walk(api, name => name === "route.ts").sort().map(file => {
  const relative = path.relative(api, file).split(path.sep).slice(0, -1);
  const pattern = "/api/" + relative.join("/");
  const importPath = path.relative(path.dirname(output), file).split(path.sep).join("/");
  return { pattern, file: path.relative(root, file).split(path.sep).join("/"), methods: exportedMethods(source(file), file), blocked: unsupported(file), importPath: importPath.startsWith(".") ? importPath : `./${importPath}` };
});

const unsupportedRoutes = routes.filter(route => route.blocked.length);
if (unsupportedRoutes.length) {
  throw new Error(`Routes still import Next.js:\n${unsupportedRoutes.map(route => `${route.pattern}: ${route.blocked.join("; ")}`).join("\n")}`);
}

const lines = [
  "// Generated by scripts/gen-core-routes.mjs; do not edit.",
  'import type { RouteDefinition } from "./router";',
  "",
  "export const routes: RouteDefinition[] = [",
  ...routes.map(route => `  { pattern: ${JSON.stringify(route.pattern)}, file: ${JSON.stringify(route.file)}, methods: ${JSON.stringify(route.methods)}, load: () => import(${JSON.stringify(route.importPath)}), },`),
  "];",
  "",
];
writeFileSync(output, lines.join("\n"));
console.log(`Generated ${routes.length} routes.`);
